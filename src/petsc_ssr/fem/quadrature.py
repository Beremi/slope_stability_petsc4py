_DEFAULT_TETRA_RULE_BY_ELEM: dict[str, int] = {
    "P1": 1,
    "P2": 11,
    "P3": 24,
    "P4": 24,
}


def available_tetra_quadrature_rules() -> tuple[int, ...]:
    return tuple(sorted(_TETRA_RULE_BUILDERS))


def _normalize_tetra_rule(rule: int | str | None, elem_type: str) -> int:
    if rule is None:
        return int(_DEFAULT_TETRA_RULE_BY_ELEM[elem_type])
    if isinstance(rule, str):
        text = str(rule).strip().lower().replace("_", "").replace("-", "")
        aliases = {
            "1": 1,
            "1pt": 1,
            "centroid": 1,
            "4": 4,
            "4pt": 4,
            "5": 5,
            "5pt": 5,
            "11": 11,
            "11pt": 11,
            "15": 15,
            "15pt": 15,
            "24": 24,
            "24pt": 24,
            "31": 31,
            "31pt": 31,
            "45": 45,
            "45pt": 45,
        }
        if text not in aliases:
            raise ValueError(f"Unsupported tetrahedral quadrature rule {rule!r}; expected one of {available_tetra_quadrature_rules()}.")
        return int(aliases[text])
    value = int(rule)
    if value not in _TETRA_RULE_BUILDERS:
        raise ValueError(f"Unsupported tetrahedral quadrature rule {rule!r}; expected one of {available_tetra_quadrature_rules()}.")
    return value


def tetra_quadrature_rule(rule: int | str | None, *, elem_type: str = "P2") -> tuple[np.ndarray, np.ndarray]:
    elem_key = str(elem_type).strip().upper()
    if elem_key not in _DEFAULT_TETRA_RULE_BY_ELEM:
        raise ValueError(f"Tetrahedral quadrature is only defined for P1/P2/P3/P4, got {elem_type!r}.")
    rule_id = _normalize_tetra_rule(rule, elem_key)
    return _TETRA_RULE_BUILDERS[rule_id]()


